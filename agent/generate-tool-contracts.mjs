// Snapshot native contracts for portable packages, which do not include the source tree.
import fs from 'node:fs';
const contracts={};
for(const name of ['runtime-action','workbench'])contracts[name]=JSON.parse(fs.readFileSync(new URL(`../contracts/json/indago.${name}.v1.schema.json`,import.meta.url),'utf8'));
const output='// Generated by generate-tool-contracts.mjs; do not edit.\nexport default '+JSON.stringify(contracts,null,2)+';\n';
const destination=new URL('./native-contracts.mjs',import.meta.url);
if(process.argv.includes('--check')){if(fs.readFileSync(destination,'utf8').replaceAll('\r\n','\n')!==output)throw Error('Native tool contracts changed; regenerate and review adapters');}
else fs.writeFileSync(destination,output);
